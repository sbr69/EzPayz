import PDFDocument from "pdfkit";
import { prisma } from "../db/client";
import { formatBaseUnits } from "../utils/amount";

/**
 * Generates a downloadable paid receipt PDF for an invoice.
 * PRD §13.1, FLOW §6.7 — the downloadable PDF receipt is the primary receipt
 * mechanism for the MVP (email deferred).
 */
export async function generateInvoicePdfBuffer(invoiceId: string, merchantId: string): Promise<Buffer | null> {
  const invoice = await prisma.invoice.findFirst({
    where: { id: invoiceId, merchantId },
    include: { lineItems: true },
  });
  if (!invoice) return null;

  const merchant = await prisma.merchant.findUnique({ where: { id: merchantId } });
  const payment = invoice.paymentId ? await prisma.paymentIntent.findUnique({ where: { id: invoice.paymentId } }) : null;

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const width = doc.page.width - 100;

    // Header
    doc.fontSize(20).font("Helvetica-Bold").text("PAYMENT RECEIPT", { align: "center" });
    doc.moveDown(0.3);
    doc.fontSize(10).font("Helvetica").fillColor("#666").text(`Invoice ${invoice.id}`, { align: "center" });
    doc.moveDown(1);

    // Merchant block
    doc.fillColor("#000").fontSize(11).font("Helvetica-Bold").text(merchant?.displayName ?? "Merchant");
    doc.font("Helvetica").fontSize(9).fillColor("#666").text(merchant?.businessEmail ?? "");
    if (merchant?.payoutWallet) {
      doc.text(`Payout wallet: ${merchant.payoutWallet}`);
    }
    doc.moveDown(1);

    // Invoice details
    doc.fillColor("#000").fontSize(10);
    doc.text(`Title: ${invoice.title}`, { width });
    if (invoice.description) doc.text(`Description: ${invoice.description}`);
    doc.text(`Status: ${invoice.status.toUpperCase()}`);
    doc.text(`Created: ${invoice.createdAt.toISOString().split("T")[0]}`);
    if (invoice.paidAt) doc.text(`Paid: ${invoice.paidAt.toISOString().split("T")[0]}`);
    if (payment?.txRef) doc.text(`Transaction: ${payment.txRef}`);
    doc.text(`Network: Whitechain Sepolia (USDT)`);
    doc.moveDown(1);

    // Line items table
    doc.font("Helvetica-Bold").text("Line Items", { underline: true });
    doc.moveDown(0.3);
    let y = doc.y;
    doc.font("Helvetica").fontSize(9);
    doc.text("Description", 50, y, { width: width * 0.5 });
    doc.text("Qty", 50 + width * 0.5, y, { width: width * 0.15, align: "right" });
    doc.text("Unit Price", 50 + width * 0.65, y, { width: width * 0.2, align: "right" });
    doc.text("Amount", 50 + width * 0.85, y, { width: width * 0.15, align: "right" });
    doc.moveTo(50, y + 12).lineTo(50 + width, y + 12).strokeColor("#ccc").stroke();
    y += 18;

    for (const item of invoice.lineItems) {
      const lineTotal = BigInt(item.unitPrice) * BigInt(item.quantity);
      doc.text(item.description, 50, y, { width: width * 0.5 });
      doc.text(String(item.quantity), 50 + width * 0.5, y, { width: width * 0.15, align: "right" });
      doc.text(formatBaseUnits(item.unitPrice), 50 + width * 0.65, y, { width: width * 0.2, align: "right" });
      doc.text(formatBaseUnits(lineTotal.toString()), 50 + width * 0.85, y, { width: width * 0.15, align: "right" });
      y += 16;
    }

    doc.moveTo(50, y).lineTo(50 + width, y).strokeColor("#ccc").stroke();
    y += 16;
    doc.font("Helvetica-Bold").fontSize(12);
    doc.text(`Total: ${formatBaseUnits(invoice.total)} USDT`, 50 + width * 0.65, y, { width: width * 0.35, align: "right" });

    // Footer
    doc.moveDown(2);
    doc.font("Helvetica").fontSize(8).fillColor("#999").text(
      "This receipt was generated by the Whitechain USDT Payment Gateway. " +
      "Settlement verified on Whitechain Sepolia. Testnet tokens have no monetary value.",
      { align: "center", width }
    );

    doc.end();
  });
}
