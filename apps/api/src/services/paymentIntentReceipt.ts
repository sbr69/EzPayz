import PDFDocument from "pdfkit";
import { prisma } from "../db/client";
import { formatBaseUnits } from "../utils/amount";

/**
 * Generates a downloadable receipt PDF directly from a payment intent — no invoice required.
 * PRD §13.1, FLOW §6.7. A receipt is a property of a payment, not an invoice.
 * Used by GET /v1/payment-intents/:id/receipt.pdf and the checkout success page.
 */
export async function generatePaymentReceiptPdfBuffer(paymentIntentId: string, merchantId: string): Promise<Buffer | null> {
  const intent = await prisma.paymentIntent.findFirst({
    where: { id: paymentIntentId, merchantId },
  });
  if (!intent) return null;

  const merchant = await prisma.merchant.findUnique({ where: { id: merchantId } });

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const width = doc.page.width - 100;

    doc.fontSize(20).font("Helvetica-Bold").text("PAYMENT RECEIPT", { align: "center" });
    doc.moveDown(0.3);
    doc.fontSize(10).font("Helvetica").fillColor("#666").text(`Receipt ${paymentIntentId}`, { align: "center" });
    doc.moveDown(1);

    doc.fillColor("#000").fontSize(11).font("Helvetica-Bold").text(merchant?.displayName ?? "Merchant");
    doc.font("Helvetica").fontSize(9).fillColor("#666").text(merchant?.businessEmail ?? "");
    if (merchant?.payoutWallet) {
      doc.text(`Payout wallet: ${merchant.payoutWallet}`);
    }
    doc.moveDown(1);

    doc.fillColor("#000").fontSize(10);
    doc.text(`Description: ${intent.description}`, { width });
    doc.text(`Amount: ${formatBaseUnits(intent.amount)} USDT`, { width });
    doc.text(`Status: ${intent.status.toUpperCase()}`);
    doc.text(`Network: Whitechain Sepolia (USDT)`);
    doc.text(`Created: ${intent.createdAt.toISOString().split("T")[0]}`);
    if (intent.settledAt) doc.text(`Settled: ${intent.settledAt.toISOString().split("T")[0]}`);
    if (intent.txRef) doc.text(`Transaction: ${intent.txRef}`);
    if (intent.payerWallet) doc.text(`Payer: ${intent.payerWallet}`);
    doc.moveDown(1);

    if (intent.refundedAmount && BigInt(intent.refundedAmount) > 0n) {
      doc.font("Helvetica-Bold").text(`Refunded: ${formatBaseUnits(intent.refundedAmount)} USDT`);
      doc.moveDown(0.5);
    }

    doc.moveDown(2);
    doc.font("Helvetica").fontSize(8).fillColor("#999").text(
      "This receipt was generated by the Whitechain USDT Payment Gateway. " +
      "Settlement verified on Whitechain Sepolia. Testnet tokens have no monetary value.",
      { align: "center", width }
    );

    doc.end();
  });
}
